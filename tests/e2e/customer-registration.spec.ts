import { expect, test } from '@playwright/test';
test('master registers fiscal, contact, address, admin and contract data', async ({ page }, testInfo) => {
  await page.route('**/api/v1/taggmaster/session', route => route.fulfill({ json: {admin:{id:'master',name:'Master Teste',email:'master@example.invalid'}} }));
  await page.route('**/api/v1/taggmaster/clients?*', route => route.fulfill({json:{items:[],total:0,page:1,pageSize:20}}));
  await page.route('https://viacep.com.br/ws/85010000/json/', route => route.fulfill({json:{logradouro:'Rua de Teste',bairro:'Centro',localidade:'Guarapuava',uf:'PR'}}));
  let submitted: Record<string, unknown> | undefined;
  await page.route('**/api/v1/taggmaster/clients', async route => {
    submitted = route.request().postDataJSON();
    await route.fulfill({status:201,json:{client:{id:'client',name:'Cliente Teste',admin:{email:'admin@example.invalid'}}}});
  });
  await page.goto('/taggmaster');
  await page.getByRole('button',{name:'+ Nova empresa'}).click();
  const form = page.locator('form.master-registration');
  await form.locator('[name=name]').fill('Cliente Teste');
  await form.locator('[name=companyName]').fill('Empresa Teste');
  await form.locator('[name=slug]').fill('cliente-teste');
  await form.locator('[name=taxId]').fill('11222333000181');
  await expect(form.locator('[name=taxId]')).toHaveValue('11.222.333/0001-81');
  await form.locator('[name=stateRegistration]').fill('ISENTO');
  await form.locator('[name=contactName]').fill('Contato Teste');
  await form.locator('[name=contactEmail]').fill('contact@example.invalid');
  await form.locator('[name=phone]').fill('42999999999');
  await expect(form.locator('[name=phone]')).toHaveValue('(42) 99999-9999');
  await form.locator('[name=postalCode]').fill('85010000');
  await expect(form.locator('[name=street]')).toHaveValue('Rua de Teste');
  await expect(form.locator('[name=city]')).toHaveValue('Guarapuava');
  await form.locator('[name=number]').fill('100');
  await form.locator('[name=adminName]').fill('Admin Teste');
  await form.locator('[name=adminEmail]').fill('admin@example.invalid');
  await form.locator('[name=adminPassword]').fill('only-test-password-123');
  await form.locator('[name=confirmPassword]').fill('only-test-password-123');
  await form.locator('[name=contractStart]').fill('2026-01-01');
  await form.locator('[name=contractEnd]').fill('2025-12-31');
  await form.getByRole('button',{name:'Cadastrar empresa e administrador'}).click();
  expect(submitted).toBeUndefined();
  expect(await form.locator('[name=contractEnd]').evaluate((input: HTMLInputElement) => input.validationMessage)).toContain('fim do contrato');
  await form.locator('[name=contractEnd]').fill('2026-12-31');
  await page.locator('dialog').evaluate(element => element.scrollTop = 0);
  await page.screenshot({path:'artifacts/customer-registration-' + testInfo.project.name + '.png',fullPage:true});
  await form.getByRole('button',{name:'Cadastrar empresa e administrador'}).click();
  await expect(page.getByRole('status').filter({hasText:'Cliente Cliente Teste cadastrado'})).toBeVisible();
  expect(submitted?.address).toMatchObject({street:'Rua de Teste',number:'100',city:'Guarapuava',state:'PR',country:'Brasil'});
  expect(submitted?.contract).toEqual({start:'2026-01-01',end:'2026-12-31'});
});
test('CEP lookup failure permits manual address', async ({page}) => {
  await page.route('**/api/v1/taggmaster/session', route=>route.fulfill({json:{admin:{id:'master',name:'Master',email:'master@example.invalid'}}}));
  await page.route('**/api/v1/taggmaster/clients?*', route=>route.fulfill({json:{items:[],total:0,page:1,pageSize:20}}));
  await page.route('https://viacep.com.br/ws/99999999/json/', route=>route.fulfill({json:{erro:true}}));
  await page.goto('/taggmaster');
  await page.getByRole('button',{name:'+ Nova empresa'}).click();
  await page.locator('[name=postalCode]').fill('99999999');
  await expect(page.locator('.master-cep-status')).toContainText('CEP não encontrado');
  await page.locator('[name=street]').fill('Rua informada manualmente');
  await expect(page.locator('[name=street]')).toHaveValue('Rua informada manualmente');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
