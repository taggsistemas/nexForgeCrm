import {afterAll,beforeAll,describe,expect,it} from 'vitest';
import {randomUUID} from 'node:crypto';
import mongoose from 'mongoose';
import request from 'supertest';
import {createApp} from '../../apps/api/src/app.js';
import {initializeClientModels,platformClients} from '../../apps/api/src/modules/platform/clients.js';
import {PlatformAdmin} from '../../apps/api/src/modules/platform/models.js';
import {User,Session,Membership} from '../../apps/api/src/modules/identity/models.js';
import {identityService} from '../../apps/api/src/modules/identity/service.js';
import {hashPassword,tokenHash,newSessionToken} from '../../apps/api/src/modules/identity/security.js';
import {initializeAccountSecurityModels,PasswordReset,RecoveryJob,PrivacyAcceptance} from '../../apps/api/src/modules/account-security/models.js';
import {dispatchPasswordRecovery} from '../../apps/api/src/modules/account-security/worker.js';
import {privacyVersion} from '../../packages/contracts/src/privacy.js';
import {customerRegistrationFixture} from '../fixtures/customer.js';
const uri=process.env.MONGODB_TEST_URI,database='nexforge_crm_test_'+randomUUID().replaceAll('-','');
describe.skipIf(!uri)('first login, privacy evidence and durable password recovery in real MongoDB',()=>{
 beforeAll(async()=>{await mongoose.connect(uri!,{dbName:database,serverSelectionTimeoutMS:10000});await Promise.all([initializeClientModels(),initializeAccountSecurityModels(),PlatformAdmin.init()]);},30000);
 afterAll(async()=>{try{if(mongoose.connection.name===database)await mongoose.connection.dropDatabase();}finally{await mongoose.disconnect();}});
 it('requires temporary password change and privacy acceptance in the backend before business access',async()=>{
  const password='temporary-password-test',personal='new-personal-password-test';
  const master=await PlatformAdmin.create({name:'Master',email:'security-master@example.invalid',passwordHash:await hashPassword(password)});
  const client=await platformClients.create({...customerRegistrationFixture,name:'Secure',slug:'secure',companyName:'Secure',adminName:'Admin',adminEmail:'security-owner@example.invalid',adminPassword:password},String(master._id));
  const origin='http://localhost:5173',app=createApp({origin,databaseReady:()=>true,identity:identityService});
  const initial=await identityService.login(client.admin!.email,password);if(!initial)throw Error('Missing initial session');
  const headers=(token:string)=>({Origin:origin,Cookie:'nf_session='+token}),crm='/api/v1/companies/'+initial.context.companyIds[0]+'/crm/leads';
  expect(initial.view.security.mustChangePassword).toBe(true);
  const blocked=await request(app).get(crm).set(headers(initial.token));
  expect(blocked.status).toBe(403);expect(blocked.body.code).toBe('PASSWORD_CHANGE_REQUIRED');
  expect((await request(app).get('/api/v1/admin/users').set(headers(initial.token))).body.code).toBe('PASSWORD_CHANGE_REQUIRED');
  expect((await request(app).post('/api/v1/auth/privacy/accept').set(headers(initial.token)).send({version:privacyVersion,accepted:true})).status).toBe(400);
  expect((await request(app).post('/api/v1/auth/password/change').set(headers(initial.token)).send({currentPassword:'wrong',newPassword:personal})).status).toBe(400);
  expect((await request(app).post('/api/v1/auth/password/change').set(headers(initial.token)).send({currentPassword:password,newPassword:personal})).status).toBe(204);
  expect(await identityService.authenticate(initial.token)).toBeNull();
  expect(await identityService.login(client.admin!.email,password)).toBeNull();
  const changed=await identityService.login(client.admin!.email,personal);if(!changed)throw Error('Missing changed session');
  expect(changed.view.security).toEqual({mustChangePassword:false,privacyAcceptanceRequired:true});
  expect((await request(app).get(crm).set(headers(changed.token))).body.code).toBe('PRIVACY_ACCEPTANCE_REQUIRED');
  expect((await request(app).post('/api/v1/auth/privacy/accept').set(headers(changed.token)).send({version:'old',accepted:true})).status).toBe(400);
  expect((await request(app).post('/api/v1/auth/privacy/accept').set(headers(changed.token)).send({version:privacyVersion,accepted:false})).status).toBe(400);
  for(let i=0;i<2;i++)expect((await request(app).post('/api/v1/auth/privacy/accept').set(headers(changed.token)).send({version:privacyVersion,accepted:true})).status).toBe(204);
  expect((await request(app).get('/api/v1/auth/session').set(headers(changed.token))).body.security.privacyAcceptanceRequired).toBe(false);
  expect(await PrivacyAcceptance.countDocuments({tenantId:initial.context.tenantId,userId:initial.context.userId,version:privacyVersion})).toBe(1);
  const acceptance=await PrivacyAcceptance.findOne({userId:initial.context.userId});
  expect(acceptance?.documentHash).toMatch(/^[a-f0-9]{64}$/);expect(acceptance?.acceptedAt).toBeInstanceOf(Date);
  const stale=newSessionToken();
  await Session.findOneAndUpdate({_id:initial.context.userId},{$set:{tokenHash:tokenHash(stale),passwordVersion:0}});
  expect(await identityService.authenticate(stale)).toBeNull();
 },30000);
 it('queues uniform requests, sends only to registered email, consumes reset once and invalidates sessions',async()=>{
  const password='reset-original-password',replacement='reset-replacement-password';
  const user=await User.create({name:'Recover',email:'recover@example.invalid',passwordHash:await hashPassword(password),mustChangePassword:true});
  const tenant=await (await import('../../apps/api/src/modules/identity/models.js')).Tenant.create({name:'Recovery',slug:'recovery'});
  const {Company,Role}=await import('../../apps/api/src/modules/identity/models.js');
  const company=await Company.create({tenantId:tenant._id,name:'Recovery'});
  const role=await Role.create({tenantId:tenant._id,name:'Seller',key:'seller',permissions:[]});
  await Membership.create({tenantId:tenant._id,userId:user._id,companyIds:[company._id],roleIds:[role._id]});
  const active=await identityService.login(user.email,password);if(!active)throw Error('Missing recovery session');
  const sent:{to:string;url:string;expiresMinutes:number}[]=[];
  const mailer=async(message:{to:string;url:string;expiresMinutes:number})=>{sent.push(message);};
  const origin='http://localhost:5173',app=createApp({origin,databaseReady:()=>true,identity:identityService,recoveryMailer:mailer});
  const send=(email:string)=>request(app).post('/api/v1/auth/password/forgot').set('Origin',origin).set('Host','untrusted.invalid').send({email});
  const known=await send(user.email),unknown=await send('unknown@example.invalid');
  expect(known.status).toBe(202);expect(unknown.status).toBe(202);expect(known.body).toEqual(unknown.body);expect(sent).toHaveLength(0);
  for(let i=0;i<3;i++)await dispatchPasswordRecovery(origin,mailer);
  expect(sent).toHaveLength(1);expect(sent[0].to).toBe(user.email);
  const url=new URL(sent[0].url);expect(url.origin).toBe(origin);expect(url.pathname).toBe('/reset-password');expect(url.search).toBe('');
  const token=new URLSearchParams(url.hash.slice(1)).get('token')!;
  expect(token).toMatch(/^[a-f0-9]{64}$/);
  const stored=await PasswordReset.findById(user._id).select('+tokenHash');
  expect(stored!.tokenHash).toBe(tokenHash(token));expect(JSON.stringify(stored)).not.toContain(token);
  expect(JSON.stringify(known.body)).not.toContain(token);
  const reset=()=>request(app).post('/api/v1/auth/password/reset').set('Origin',origin).send({token,newPassword:replacement});
  const results=await Promise.all([reset(),reset()]);
  expect(results.map(result=>result.status).sort()).toEqual([204,400]);
  expect(await PasswordReset.findById(user._id)).toBeNull();expect(await identityService.authenticate(active.token)).toBeNull();
  expect(await identityService.login(user.email,password)).toBeNull();
  expect((await identityService.login(user.email,replacement))?.view.security.mustChangePassword).toBe(false);
  await send(user.email);await dispatchPasswordRecovery(origin,mailer);
  const expired=new URLSearchParams(new URL(sent[sent.length-1].url).hash.slice(1)).get('token');
  await PasswordReset.updateOne({_id:user._id},{$set:{expiresAt:new Date(0)}});
  expect((await request(app).post('/api/v1/auth/password/reset').set('Origin',origin).send({token:expired,newPassword:'another-personal-password'})).status).toBe(400);
  const disabled=createApp({origin,databaseReady:()=>true,identity:identityService});
  expect((await request(disabled).post('/api/v1/auth/password/forgot').set('Origin',origin).send({email:user.email})).status).toBe(503);
  expect(await RecoveryJob.countDocuments({state:'processing'})).toBe(0);
 },30000);
});
